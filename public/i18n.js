let lang = 'en';
const langListeners = [];

// Kayıtlı seçim > tarayıcı/sistem dili > İngilizce
function detectLang() {
  try {
    const saved = localStorage.getItem('lang');
    if (STRINGS[saved]) return saved;
  } catch {}
  for (const l of navigator.languages || [navigator.language]) {
    const code = String(l || '').toLowerCase().split('-')[0];
    if (STRINGS[code]) return code;
  }
  return 'en';
}

function t(key, vars) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}

function applyStatic() {
  const root = document.documentElement;
  root.lang = lang;
  root.dir = RTL_LANGS.includes(lang) ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const label = t(el.dataset.i18nTitle);
    el.title = el.dataset.key ? `${label} (${el.dataset.key})` : label;
    el.setAttribute('aria-label', label);
  });
}

function setLang(code, save) {
  if (!STRINGS[code]) code = 'en';
  lang = code;
  if (save) {
    try { localStorage.setItem('lang', code); } catch {}
  }
  applyStatic();
  document.querySelectorAll('select.lang').forEach((s) => { s.value = code; });
  langListeners.forEach((fn) => fn());
}

function onLangChange(fn) { langListeners.push(fn); }

function initLangSelects() {
  document.querySelectorAll('select.lang').forEach((sel) => {
    sel.replaceChildren(...LANGS.map(([code, name]) => new Option(name, code)));
    sel.addEventListener('change', () => setLang(sel.value, true));
  });
  setLang(detectLang(), false);
}
